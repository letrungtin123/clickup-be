/**
 * LOCAL DEVELOPMENT ONLY — SPEC §10: replays the anonymized worklog through the real production
 * workflow engine (task creation, status moves, scoring hooks) with the historical times, then prints a
 * reconciliation of WORKER credits per person against the CSV (PD-010: QC credit is per task, so the
 * Checking rows become qc assignments, not tasks).
 *
 *   npx tsx scripts/seed-from-worklog.ts \
 *     --rules ../docs/retouch/seed/seed_credit_rules_T5_2026.csv \
 *     --log ../docs/retouch/seed/seed_worklog_T5_2026.csv [--inflight 0.1] [--seed 42]
 *
 * Idempotent: previous seed jobs (tag "seed") and their tasks, logs and score entries are removed first.
 * Seed account passwords are written to BE/.env.seed-worklog (git-ignored) and never printed.
 */
