// Arguments & safety -------------------------------------------------------------------------------------

const args = new Map<string, string>();
for (let index = 2; index < process.argv.length; index += 1) {
  const key = process.argv[index]!;
  if (key.startsWith("--")) {
    args.set(key.slice(2), process.argv[index + 1] && !process.argv[index + 1]!.startsWith("--") ? process.argv[++index]! : "true");
  }
}
const rulesPath = resolve(args.get("rules") ?? "../docs/retouch/seed/seed_credit_rules_T5_2026.csv");
const logPath = resolve(args.get("log") ?? "../docs/retouch/seed/seed_worklog_T5_2026.csv");
const inflight = Number(args.get("inflight") ?? "0");
let randomState = Number(args.get("seed") ?? "42") >>> 0 || 42;
const random = () => {
  // Deterministic xorshift so a given --seed reproduces the same in-flight sample.
  randomState ^= randomState << 13;
  randomState ^= randomState >>> 17;
  randomState ^= randomState << 5;
  return (randomState >>> 0) / 4_294_967_296;
};

const isLoopback = (value: string) => {
  try {
    const host = new URL(value).hostname;
    return host === "127.0.0.1" || host === "localhost" || host === "[::1]";
  } catch {
    return false;
  }
};
const supabaseUrl = process.env.SUPABASE_URL ?? "";
const serviceKey = process.env.SUPABASE_SERVICE_ROLE_KEY ?? "";
if (!isLoopback(supabaseUrl) || !isLoopback(process.env.DATABASE_URL ?? "") || !serviceKey) {
  console.error("Refusing to seed: SUPABASE_URL and DATABASE_URL must point at the local stack.");
  process.exit(1);
}
if (!(inflight >= 0 && inflight <= 1)) {
  console.error("--inflight must be between 0 and 1.");
  process.exit(1);
}

